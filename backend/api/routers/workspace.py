"""Project Workspace (Surface #7): docs/API_CONTRACT_P9.md §7,
docs/PROJECT_AND_STACK.md §2, ADR 0006. The P8-T03 scope, absorbed into P9-T03.

**RBAC.** Surface `project_workspace`. Reads (workspace, files list,
download, activity) need READ: Portfolio Manager, Hub Planner, Engineer,
Executive Viewer, Admin, Super Admin. Every mutation needs WRITE: Portfolio
Manager, Hub Planner, Admin, Super Admin. Mutations are stage progress,
recalculate, file upload/edit and comment create/edit/delete.

**2026-09-30 (ADR 0012, P10-T02).** The role-level check above is necessary
but no longer sufficient by itself for gating mutations: every mutating
endpoint below also accepts a project-scoped `ProjectAccessGrant` via
`services.project_access.authorize_project_action` (never a duplicate of the
role check — that function composes with it). An Editor-level grant may
perform exactly three actions: stage-progress PATCH, file upload, and
comment post; every other mutation (file rename/recategorise, comment
edit/delete, recalculate) needs an Admin-level grant, same as a role that
already has Workspace WRITE. Read endpoints compose the same way one layer
down, in `services.workspace.get_scoped_project_or_404`: an active grant can
surface a project the caller's hub scope/own-assignment alone would not.

**Row scoping (P3-T03 pattern).** Every endpoint resolves the project
through `services.workspace.get_scoped_project_or_404`. Hub Planners see
their own hubs only; an Engineer sees their own assignments only. Out of
scope gives 404, exactly like a nonexistent project.

**Frozen projects (ruling 3).** Stage progress cannot be edited on a frozen
project: the stage PATCH returns 409 `PROJECT_FROZEN` ("Unfreeze on the Gantt
to record stage progress"). ADR 0006 already kept `frozen` and stage progress
apart; this enforces it.

**Progress edits never solve (ADR 0006).** `PATCH …/stages/{step_id}` sets
`schedule_stale` and writes an audit row. The row records the blocked
reason's length, not its text. A transition *into* Blocked also sends a
`stage_blocked` notification to the Hub Planners of the project's hub and to
Portfolio Managers (`services.notifications.
generate_stage_blocked_notifications`). The message holds project, hub,
stage and reason only; no person's name (OQ#8). `POST …/recalculate` is the only
thing that schedules. It dispatches the **greedy** scheduler through the
P3-T06 Celery lifecycle (`workers.schedule_tasks.run_greedy_schedule`, with
`activate=True`). CP-SAT is not used here: docs/OPEN_QUESTIONS.md #10 blocks
exposing CP-SAT through a user-facing action until the client answers
(P9-T03 follow-up). The admin-only `POST /schedule-runs/cp-sat-dispatch` is
unchanged. The completed run becomes the active schedule, clears the stale
flags, and writes the "Schedule recalculated — finish moved week X → week Y"
event.
Every recalculation creates a new `ScheduleRun` row (I14). A recalculation
is refused with 409 `RUN_IN_PROGRESS` while another solver run started
recently is still queued or running, so two activations cannot race.

**Files (MinIO).** The extension must be on the allowlist, the bytes must
match it (`services.file_sniff`), and the size is capped at 50 MB (413
`FILE_TOO_LARGE`). The object key is generated by the server
(`projects/<project_id>/files/<uuid4 hex>`) and never derived from the
display name or the uploaded filename. Re-uploading an existing display name
creates version N+1. Downloads stream from MinIO with a sanitised
`Content-Disposition` and `X-Content-Type-Options: nosniff`. The reverse
proxy should also cap request bodies (for example `client_max_body_size`):
the 50 MB check here runs after the multipart body has been received.

**Comments.** Markdown is stored and returned as written (`body_md`, at most
10 000 characters, 422 above). The server no longer renders HTML (P9-R02,
security S-02: re-rendering every comment on every read could stall the
event loop, and nothing consumed it); the frontend renders `body_md` with its
own React-elements-only renderer. Comment creation is rate-limited per user
(`COMMENT_RATE_LIMIT`, in-process token bucket, 429 `RATE_LIMITED` with
`Retry-After`; see `services.rate_limit` for its limits). Only the author may edit, and only
within 15 minutes (403 `EDIT_LOCKED`; 403 `NOT_AUTHOR` for anyone else).
Deletion is soft (`soft_deleted_at`; the DB trigger forbids a hard delete),
by the author or an Admin / Super Admin. Audit rows for comments record
ids and lengths, never the text: comments may contain personal data, and
the audit log is immutable.

**OQ#8.** Person names are withheld exactly as the P3-T09 pattern decides.
See `schemas/workspace.py`. `@mentions` are not resolved and
`mentioned_user_ids` is always empty until the DPO signs off. A mention
notification would also need a new `NotificationReason`, which is deferred
with it.
"""

