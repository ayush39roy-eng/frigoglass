@router.get("/{project_id}/files/{file_id}/download")
async def download_file(
    project_id: uuid.UUID,
    file_id: uuid.UUID,
    db: AsyncSession = Depends(get_db),
    current_user: Principal = Depends(_read),
) -> StreamingResponse:
    project = await _project_or_404(db, project_id, current_user)
    record = await _file_or_404(db, project, file_id)
    client = get_minio_client()
    bucket = get_minio_settings().attachments_bucket
    try:
        obj = await run_in_threadpool(client.get_object, bucket, record.minio_object_key)
    except S3Error as exc:
        raise HTTPException(
            status_code=status.HTTP_502_BAD_GATEWAY,
            detail="Failed to retrieve the file from object storage",
        ) from exc

    def _iter() -> Iterator[bytes]:
        try:
            yield from obj.stream(64 * 1024)
        finally:
            obj.close()
            obj.release_conn()

    return StreamingResponse(
        _iter(),
        media_type=record.content_type,
        headers={
            "Content-Disposition": _content_disposition(record.display_name, record.content_type),
            "Content-Length": str(record.size_bytes),
            "X-Content-Type-Options": "nosniff",
            "Cache-Control": "private, no-store",
        },
    )


