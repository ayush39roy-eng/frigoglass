# --- Stage progress (DOMAIN_RULES "Per-stage progress fields") ------------------------


@router.patch("/{project_id}/stages/{step_id}", response_model=WorkspaceRead)
async def patch_stage(
    project_id: uuid.UUID,
    step_id: str,
    body: StageUpdateRequest,
    db: AsyncSession = Depends(get_db),
    current_user: Principal = Depends(get_current_principal),
) -> WorkspaceRead:
    project = await _project_or_404(db, project_id, current_user)
    # ADR 0012: stage-progress PATCH is one of the three actions an
    # Editor-level `ProjectAccessGrant` may perform (the other two are file
    # upload and comment post) — never a Registration charter field,
    # freeze/unfreeze, or precedence edit.
    await authorize_project_action(
        db, current_user, project,
        surface=Surface.PROJECT_WORKSPACE, action=Action.WRITE, min_grant_role="editor",
    )
    if project.frozen:
        raise CodedHTTPException(
            status.HTTP_409_CONFLICT,
            "PROJECT_FROZEN",
            "This project is frozen. Unfreeze on the Gantt to record stage progress.",
        )
    try:
        await sync_project_steps(db, project, project.hub.is_oem)
    except WorkflowChangeWithProgress as exc:  # pragma: no cover - needs corrupt data
        raise CodedHTTPException(
            HTTP_422, "WORKFLOW_CHANGE_WITH_PROGRESS", str(exc)
        ) from exc
    row = (
        await db.execute(
            select(ProjectWorkflowStep).where(
                ProjectWorkflowStep.project_id == project.id,
                ProjectWorkflowStep.step_template_id == step_id,
            )
        )
    ).scalar_one_or_none()
    if row is None:
        raise HTTPException(
            status_code=status.HTTP_404_NOT_FOUND,
            detail=f"Stage {step_id!r} is not a stage of this project's workflow",
        )
    if row.duration_weeks == 0:
        raise CodedHTTPException(
            HTTP_422,
            "STAGE_SKIPPED",
            f"Stage {step_id!r} is skipped for this project (0 weeks) and has no progress "
            "of its own.",
        )

    explicit = body.model_dump(exclude_unset=True)
    if "status" in explicit and explicit["status"] is None:
        raise CodedHTTPException(
            HTTP_422,
            "STAGE_INCONSISTENT",
            [field_error("status", "may not be null")],
        )
    if "percent_complete" in explicit and explicit["percent_complete"] is None:
        raise CodedHTTPException(
            HTTP_422,
            "STAGE_INCONSISTENT",
            [field_error("percent_complete", "may not be null")],
        )
    merged, errors = merge_stage_update(row, explicit)
    if errors:
        raise CodedHTTPException(
            HTTP_422,
            "STAGE_INCONSISTENT",
            [field_error(name, msg) for name, msg in errors],
        )

    before_state = _stage_state(project, row)
    was_blocked = row.status == WorkflowStepStatus.BLOCKED
    for name, value in merged.items():
        setattr(row, name, value)
    await db.flush()
    await mark_projects_stale(db, [project.id])
    if row.status == WorkflowStepStatus.BLOCKED and not was_blocked:
        # P9-T03 follow-up: a Blocked stage "surfaces on Notifications".
        step_name = (
            await db.execute(
                select(WorkflowStepTemplate.name).where(WorkflowStepTemplate.id == step_id)
            )
        ).scalar_one()
        await generate_stage_blocked_notifications(
            db,
            project=project,
            hub_name=project.hub.name.value,
            step_id=step_id,
            step_name=step_name,
            reason=row.blocked_reason or "",
            actor_user_id=current_user.user_id,
        )
    db.add(
        AuditLogEntry(
            actor_user_id=current_user.user_id,
            action="project_stage.update",
            entity_type="ProjectWorkflowStep",
            entity_id=str(row.id),
            hub_id=project.hub_id,
            before_state=before_state,
            after_state=_stage_state(project, row),
        )
    )
    await db.commit()
    await db.refresh(project)
    return await build_workspace(db, project, current_user)


def _stage_state(project: Project, row: ProjectWorkflowStep) -> dict[str, Any]:
    return {
        "project_id": str(project.id),
        "step_id": row.step_template_id,
        "status": row.status.value,
        "percent_complete": row.percent_complete,
        "actual_start_week": row.actual_start_week,
        "actual_end_week": row.actual_end_week,
        "remaining_weeks_override": row.remaining_weeks_override,
        # The reason is free text and may contain personal data; the audit
        # log is immutable, so only its length is recorded (like comments).
        "blocked_reason_length": len(row.blocked_reason) if row.blocked_reason else 0,
    }


# --- Recalculate (ADR 0006, I14) ------------------------------------------------------


@router.post(
    "/{project_id}/recalculate",
    response_model=RecalculateResponse,
    status_code=status.HTTP_202_ACCEPTED,
)
async def recalculate(
    project_id: uuid.UUID,
    db: AsyncSession = Depends(get_db),
    current_user: Principal = Depends(get_current_principal),
) -> RecalculateResponse:
    project = await _project_or_404(db, project_id, current_user)
    # ADR 0012: recalculate is NOT one of the Editor grant's three permitted
    # actions, so it needs project-scoped Admin (or the unchanged role-level
    # WRITE this endpoint already required).
    await authorize_project_action(
        db, current_user, project,
        surface=Surface.PROJECT_WORKSPACE, action=Action.WRITE, min_grant_role="admin",
    )

    window = timedelta(seconds=get_celery_settings().task_time_limit_seconds + 120)
    in_flight = (
        await db.execute(
            select(ScheduleRun.id)
            .where(
                ScheduleRun.status.in_([ScheduleRunStatus.QUEUED, ScheduleRunStatus.RUNNING]),
                ScheduleRun.created_at > datetime.now(UTC) - window,
            )
            .limit(1)
        )
    ).scalar_one_or_none()
    if in_flight is not None:
        raise CodedHTTPException(
            status.HTTP_409_CONFLICT,
            "RUN_IN_PROGRESS",
            f"A schedule run ({in_flight}) is already queued or running. Follow its progress "
            "and try again when it finishes.",
        )

    # GREEDY, not CP-SAT: docs/OPEN_QUESTIONS.md #10 blocks exposing CP-SAT
    # through a user-facing action until the client answers.
    run = await create_queued_schedule_run(
        db,
        solver_type=SolverType.GREEDY,
        trigger_reason="workspace_recalc",
        triggered_by_user_id=current_user.user_id,
    )
    async_result = run_greedy_schedule.delay(
        str(run.id),
        triggered_by_user_id=str(current_user.user_id),
        activate=True,
        recalc_project_id=str(project.id),
    )
    run.celery_task_id = async_result.id
    db.add(run)
    db.add(
        AuditLogEntry(
            actor_user_id=current_user.user_id,
            action="project.recalculate_requested",
            entity_type="Project",
            entity_id=str(project.id),
            hub_id=project.hub_id,
            before_state=None,
            after_state={
                "project_id": str(project.id),
                "schedule_run_id": str(run.id),
                "schedule_run_version": run.version,
                "celery_task_id": run.celery_task_id,
            },
        )
    )
    await db.commit()
    publish_progress(str(run.id), status="queued")
    return RecalculateResponse(schedule_run_id=run.id, task_id=str(async_result.id))


